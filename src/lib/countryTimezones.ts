function normalizeCountryKey(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

/** Επιστρέφει ISO2 κωδικό από κωδικό ή όνομα χώρας (όπως έρχεται από το CMS). */
export function resolveCountryCode(
  value: string | null | undefined,
): string | null {
  const raw = String(value ?? "").trim();
  if (!raw) return null;
  if (raw.length === 2) {
    const code = raw.toUpperCase();
    return COUNTRY_TIMEZONE[code] ? code : null;
  }
  const byName = COUNTRY_NAME_TO_CODE[normalizeCountryKey(raw)];
  if (byName) return byName;
  // Δοκίμασε και με πεζά/τόνους στο πρωτότυπο κλειδί.
  const direct = COUNTRY_NAME_TO_CODE[raw.toLowerCase()];
  return direct ?? null;
}

/** Ζώνη ώρας της χώρας διεξαγωγής (π.χ. BE → Europe/Brussels). */
export function getCountryTimezone(
  value: string | null | undefined,
): string | null {
  const code = resolveCountryCode(value);
  if (!code) return null;
  return COUNTRY_TIMEZONE[code] ?? null;
}

/** Όλες οι ζώνες που μπορεί να χρειαστούν για μια χώρα (για τη λίστα επιλογών). */
export function getCountryTimezoneOptions(
  value: string | null | undefined,
): string[] {
  const zone = getCountryTimezone(value);
  return zone ? [zone] : [];
}
